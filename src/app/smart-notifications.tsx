import { RefreshControl, ScrollView, StyleSheet, View } from "react-native";

import {
  NotificationHero,
  NotificationSection,
  NotificationStatGrid,
  ReminderList,
  ReminderSettingsCard,
} from "../components/notifications";
import { CommonBackButton, ErrorState, LoadingState, Screen } from "../components/common";
import { useAuth } from "../context/AuthContext";
import { useSmartNotifications } from "../hooks";
import { colors, spacing } from "../theme";

export default function SmartNotificationsScreen() {
  const { user, authSessionId } = useAuth();
  return user ? <AccountSmartNotifications key={authSessionId} /> : null;
}

function AccountSmartNotifications() {
  const {
    data,
    loading,
    refreshing,
    saving,
    error,
    refresh,
    updateSettings,
    updateReminderStatus,
  } = useSmartNotifications();

  if (loading && !data) {
    return (
      <Screen>
        <View style={styles.centerState}>
          <LoadingState message="Loading smart notifications..." />
        </View>
      </Screen>
    );
  }

  if (error && !data) {
    return (
      <Screen>
        <View style={styles.centerState}>
          <ErrorState title="Unable to load reminders" message={error} onRetry={refresh} />
        </View>
      </Screen>
    );
  }

  function handleTogglePreference(
    key: "hydration" | "sleep" | "yoga" | "aiMemory" | "weeklyInsight",
    enabled: boolean
  ) {
    const preferenceUpdate = { enabled };

    if (key === "hydration") updateSettings({ hydration: preferenceUpdate });
    if (key === "sleep") updateSettings({ sleep: preferenceUpdate });
    if (key === "yoga") updateSettings({ yoga: preferenceUpdate });
    if (key === "aiMemory") updateSettings({ aiMemory: preferenceUpdate });
    if (key === "weeklyInsight") updateSettings({ weeklyInsight: preferenceUpdate });
  }

  return (
    <Screen>
      <ScrollView
        contentContainerStyle={styles.content}
        refreshControl={<RefreshControl refreshing={refreshing} onRefresh={refresh} />}
      >
        <CommonBackButton />

        {data ? (
          <>
            <NotificationHero enabled={data.settings.enabled} nextReminder={data.nextReminder} />

            <NotificationSection
              title="Learning Statistics"
              subtitle="Live reminder metrics powered by settings, wellness profile and AI memory."
            >
              <NotificationStatGrid stats={data.statistics} />
            </NotificationSection>

            <NotificationSection
              title="Reminder Controls"
              subtitle="Production-ready settings stored per user and ready for push, voice, premium and family expansion."
            >
              <ReminderSettingsCard
                settings={data.settings}
                saving={saving}
                onToggleEngine={(enabled) => updateSettings({ enabled })}
                onTogglePreference={handleTogglePreference}
              />
            </NotificationSection>

            <NotificationSection
              title="Active Reminders"
              subtitle="Scheduled nudges generated by the smart reminder engine."
            >
              <ReminderList
                reminders={data.activeReminders}
                saving={saving}
                emptyText="No active reminders right now. Enable reminders or refresh after adding wellness activity."
                onStatusChange={updateReminderStatus}
              />
            </NotificationSection>

            <NotificationSection
              title="Completed Reminders"
              subtitle="Healthy actions completed from reminder nudges."
            >
              <ReminderList
                reminders={data.completedReminders}
                saving={saving}
                emptyText="Completed reminders will appear here."
                onStatusChange={updateReminderStatus}
              />
            </NotificationSection>
          </>
        ) : null}
      </ScrollView>
    </Screen>
  );
}

const styles = StyleSheet.create({
  content: {
    paddingHorizontal: spacing.xl,
    paddingTop: 58,
    paddingBottom: 42,
    gap: spacing.xl,
  },
  centerState: {
    flex: 1,
    paddingHorizontal: spacing.xl,
    alignItems: "center",
    justifyContent: "center",
  },
});
