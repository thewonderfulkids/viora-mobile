export async function getProgramContent(): Promise<AdminManagedContent[]> {
  const remote = await listActiveProgramContent();
  const usefulRemote = remote.filter((item) => ["video", "program", "music"].includes(item.kind));
  return usefulRemote.length ? usefulRemote : FALLBACK_CONTENT;
}

export async function getCategoryProgramContent(category: AdminContentCategory): Promise<AdminManagedContent[]> {
  const content = await getProgramContent();
  return content.filter((item) => item.category === category);
}

export async function getHomeWorkoutContent(): Promise<AdminManagedContent[]> {
  return getCategoryProgramContent("home_workout");
}
